//! The closures between the CAD kernel and the solvers, exercised end to
//! end: a CAD body in the flow solver, a CAD stack in the optics solver,
//! and a CAD label grid as a material map.

use std::f64::consts::PI;

use cad::sim::{label_grid, LayerStack};
use cad::sketch::Region2;
use cad::solid::Solid;
use cad::{meshing::Grid3, Params};

#[test]
fn meshed_cad_geometry_reproduces_its_analytic_distance() {
    // The chain the flow solver depends on: Solid -> surface nets ->
    // geometry::Sdf. Its error is the mesh's, which must fall with the
    // cell size.
    let r = 0.05;
    let sphere = Solid::sphere([0.0; 3], r);
    let mut errors = Vec::new();
    for div in [8.0, 16.0] {
        let sdf = cad::sim::body_sdf(&sphere, r / div).expect("sdf");
        let mut worst: f64 = 0.0;
        for i in 0..400 {
            let a = 2.0 * PI * i as f64 / 400.0;
            let b = PI * (i as f64 / 400.0 - 0.5);
            for s in [0.5, 0.9, 1.1, 2.0] {
                let p = [s * r * b.cos() * a.cos(), s * r * b.cos() * a.sin(), s * r * b.sin()];
                let exact = s * r - r;
                worst = worst.max((sdf.distance(p) - exact).abs());
            }
        }
        errors.push(worst / r);
    }
    let order = (errors[0] / errors[1]).log2();
    assert!(order > 1.5, "distance error order {order:.2} ({errors:?})");
    assert!(errors[1] < 2e-3, "distance error {:e} at r/16", errors[1]);
}

#[test]
fn a_cad_body_in_the_flow_solver_matches_the_primitive_one() {
    // The same cylinder twice: once generated by the CAD kernel and
    // meshed, once from `geometry::primitives`. The flow solver must give
    // the same drag, which checks the whole body path — mesh, signed
    // distance, normals and the immersed forcing.
    use immersed::solver::{Bc, Body, Solver};
    use immersed::Grid;

    let (h, d) = (0.01, 0.1);
    let n = [40usize, 20, 1];
    let grid = Grid::new(n, h, [0.0, 0.0, 0.0]);
    let centre = [0.1, 0.1, 0.5 * h];
    let span = 4.0 * h;

    let cad_body = Solid::cylinder(
        [centre[0], centre[1], centre[2] - span],
        [centre[0], centre[1], centre[2] + span],
        0.5 * d,
    );
    let cad_sdf = cad::sim::body_sdf(&cad_body, d / 32.0).expect("cad sdf");
    let primitive = geometry::primitives::cylinder_z(
        [centre[0], centre[1], centre[2] - span],
        0.5 * d,
        2.0 * span,
        128,
    );
    let prim_sdf = geometry::Sdf::new(primitive);

    let u0 = 0.05;
    let nu = u0 * d / 20.0; // Re = 20
    let mut drags = Vec::new();
    for sdf in [cad_sdf, prim_sdf] {
        let bcs = [
            [Bc::inlet(move |_, _| [u0, 0.0, 0.0]), Bc::Outlet],
            [Bc::wall(), Bc::wall()],
            [Bc::Periodic, Bc::Periodic],
        ];
        let mut solver = Solver::new(grid, nu, 1.0, bcs, vec![Body::fixed(sdf)]);
        let (steps, _) = solver.run_until_steady(0.8, 4.0, 1e-5);
        assert!(steps > 10, "the solve did not advance");
        drags.push(solver.body_force_momentum(0)[0]);
    }
    let rel = (drags[0] - drags[1]).abs() / drags[1].abs();
    println!("drag: CAD body {:e} N, primitive body {:e} N ({rel:.3e})", drags[0], drags[1]);
    assert!(drags[1] > 0.0, "drag should oppose the flow");
    // Two different tessellations of the same cylinder: the difference is
    // the tessellations', not the solver's.
    assert!(rel < 0.02, "CAD and primitive bodies differ in drag by {rel:.3e}");
}

#[test]
fn a_cad_layer_stack_drives_the_optics_solver() {
    // A quarter-wave antireflection coating generated as a stack, solved
    // by `photonics::multilayer`, against the exact condition: a single
    // layer of index sqrt(n_glass) and optical thickness lambda/4 gives
    // exactly zero reflectance at normal incidence.
    use photonics::multilayer::{Layer as OpticalLayer, Stack};
    use photonics::Polarization;

    let lambda = 550e-9;
    let n_glass: f64 = 1.52;
    let n_coat = n_glass.sqrt();
    let stack = LayerStack::new(vec![
        cad::sim::Layer::new("MgF2-like", lambda / (4.0 * n_coat)).optical(n_coat, 0.0),
    ]);
    let optical = stack.optical().expect("optical constants");
    assert_eq!(optical.len(), 1);
    let layers: Vec<OpticalLayer> = optical
        .iter()
        .map(|&(t, n, k)| OpticalLayer::new(n, k, t))
        .collect();
    let solution = Stack::new(1.0, layers, n_glass).solve(lambda, 0.0, Polarization::TE);
    assert!(
        solution.reflectance < 1e-12,
        "the ideal quarter-wave coating must not reflect: R = {:e}",
        solution.reflectance
    );

    // Detuned by a quarter wave in thickness, it reflects what the bare
    // interface does: a half-wave layer is absent at this wavelength.
    let half = LayerStack::new(vec![
        cad::sim::Layer::new("MgF2-like", lambda / (2.0 * n_coat)).optical(n_coat, 0.0),
    ]);
    let layers: Vec<OpticalLayer> = half
        .optical()
        .unwrap()
        .iter()
        .map(|&(t, n, k)| OpticalLayer::new(n, k, t))
        .collect();
    let bare = ((1.0 - n_glass) / (1.0 + n_glass)).powi(2);
    let r = Stack::new(1.0, layers, n_glass).solve(lambda, 0.0, Polarization::TE).reflectance;
    assert!((r - bare).abs() < 1e-12, "half-wave layer: R = {r:e}, bare interface {bare:e}");

    // A stack missing its optical constants says so instead of guessing.
    let incomplete = LayerStack::new(vec![cad::sim::Layer::new("unknown", 1e-6)]);
    assert!(incomplete.optical().is_err());
}

#[test]
fn a_pcb_stack_gives_its_series_thermal_resistance() {
    use cad::kits::pcb::{Board, PcbLayer, KAPPA_CU, OZ_COPPER};
    let board = Board::new(
        Region2::rect([0.0, 0.0], [0.05, 0.04]),
        vec![
            PcbLayer::Copper { ounces: 2.0 },
            PcbLayer::Dielectric {
                material: "FR-4".into(),
                thickness: 0.8e-3,
                eps_r: 4.4,
                loss_tangent: 0.02,
                kappa: 0.29,
            },
            PcbLayer::Copper { ounces: 2.0 },
        ],
    );
    let r = board.layer_stack().thermal_resistance().unwrap();
    let expect = 0.8e-3 / 0.29 + 2.0 * (2.0 * OZ_COPPER) / KAPPA_CU;
    assert!((r - expect).abs() / expect < 1e-12);
    // The dielectric dominates: copper contributes under a part in 1e4.
    let copper_share = 2.0 * (2.0 * OZ_COPPER) / KAPPA_CU / r;
    assert!(copper_share < 2e-4, "copper share {copper_share:e}");
}

#[test]
fn a_label_grid_is_a_material_map_with_exact_fractions() {
    // Two concentric slabs in a box: the volume fractions must match the
    // analytic ones to the quadrature's second order.
    let outer = Solid::box_between([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let inner = Solid::box_between([0.25, 0.25, 0.0], [0.75, 0.75, 1.0]);
    let grid = Grid3::covering(([0.0; 3], [1.0; 3]), 1.0 / 40.0, 0).unwrap();
    let labels = label_grid(grid, "air", &[("core", &inner), ("shell", &outer)]);
    let f = labels.fractions();
    assert_eq!(labels.names, vec!["air", "core", "shell"]);
    // The first match wins, so the core is not double counted.
    assert!((f[1] - 0.25).abs() < 1e-12, "core fraction {:.6}", f[1]);
    assert!((f[2] - 0.75).abs() < 1e-12, "shell fraction {:.6}", f[2]);
    assert!(f[0] < 1e-12, "the box fills the domain");

    // Per-material properties become a field the solvers can take.
    let kappa = labels.property(&[0.026, 401.0, 0.29]);
    assert_eq!(kappa.len(), 40 * 40 * 40);
    let mean = kappa.iter().sum::<f64>() / kappa.len() as f64;
    let expect = 0.25 * 401.0 + 0.75 * 0.29;
    assert!((mean - expect).abs() / expect < 1e-9, "mean kappa {mean:.4} vs {expect:.4}");
}

#[test]
fn a_json_model_round_trips_to_a_solver_ready_body() {
    // The path a user actually takes: a parametric JSON model, built,
    // meshed, and checked as a flow-solver body. The bore profile is the
    // whole meridian section, crossing the axis, so the axis is interior
    // to the revolved void (see Solid::Revolve).
    let dir = std::env::temp_dir().join("cad-integration-test");
    let _ = std::fs::remove_dir_all(&dir);
    let text = r#"{
      "name": "venturi",
      "params": { "bore": 0.02, "throat": 0.01, "length": 0.06, "wall": 0.002 },
      "shape": {
        "op": "difference",
        "a": { "op": "cylinder_z", "center": [0,0,0], "radius": "bore/2 + wall",
               "height": "length" },
        "b": { "op": "revolve", "sketch": {
                 "op": "polygon",
                 "loops": [[["-bore/2", "-length/2"], ["bore/2", "-length/2"],
                            ["throat/2", 0], ["bore/2", "length/2"],
                            ["-bore/2", "length/2"], ["-throat/2", 0]]] } }
      }
    }"#;
    let model = cad::model::Model::from_json(text).expect("parse");
    let solid = model.build(&Params::new(), ".").expect("build");
    // The throat is open and the wall is solid.
    assert!(solid.sdf([0.0, 0.0, 0.0]) > 0.0, "the throat must be open");
    assert!(solid.sdf([0.0115, 0.0, 0.0]) < 0.0, "the wall must be solid");
    let body = cad::sim::case_body(&solid, 0.0006, &dir, "venturi").expect("case body");
    assert_eq!(body["file"], "venturi.stl");
    assert!(dir.join("venturi.stl").exists());

    // And the written STL reads back as the same watertight surface.
    let read = geometry::TriMesh::read(dir.join("venturi.stl")).expect("read stl");
    let report = read.report();
    assert!(report.watertight, "{report:?}");
    // A narrower throat removes material, so the solid gets bigger.
    let mut over = Params::new();
    over.set("throat", 0.006);
    let narrow = model.build(&over, ".").expect("rebuild");
    let v0 = solid.volume_quadrature(solid.bbox(), 0.0005);
    let v1 = narrow.volume_quadrature(narrow.bbox(), 0.0005);
    assert!(v1 > v0, "narrowing the throat should add material: {v1:e} vs {v0:e}");
    let _ = std::fs::remove_dir_all(&dir);
}
